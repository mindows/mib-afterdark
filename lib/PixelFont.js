// Cells across one line of `text`, including one blank column between glyphs.
function measure(text) {
  var s = String(text)
  return s.length === 0 ? 0 : s.length * 4 - 1
}

function glyph(ch) {
  var g = glyphs[ch]
  if (!g) g = glyphs[String(ch).toUpperCase()]
  return g || glyphs["?"]
}
